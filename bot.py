def fuzzy_match(user_answer: str, correct: str, threshold: float = 0.82) -> bool:
    """
    Нечёткое сравнение строк для обработки опечаток.
    Возвращает True если схожесть >= threshold.
    Также проверяет точное вхождение после нормализации.
    """
    ua = user_answer.strip().lower()
    ca = correct.strip().lower()
    
    # Точное совпадение
    if ua == ca:
        return True
    
    # Проверка содержания (короткий ответ внутри длинного)
    if len(ca) >= 3 and (ua in ca or ca in ua):
        return True
    
    # Нечёткое сравнение
    ratio = SequenceMatcher(None, ua, ca).ratio()
    return ratio >= threshold


def fuzzy_match_any(user_answer: str, correct_list: list, threshold: float = 0.82) -> bool:
    """Проверка на совпадение с любым вариантом из списка."""
    return any(fuzzy_match(user_answer, c, threshold) for c in correct_list)


def _hangman_display(word: str, guessed: set) -> str:
    """Отображение загадываемого слова с угаданными буквами."""
    result = []
    for ch in word.lower():
        if ch in guessed or ch == '-' or ch == ' ':
            result.append(ch.upper() if ch not in ('-', ' ') else ch)
        else:
            result.append('_')
    return ' '.join(result)


