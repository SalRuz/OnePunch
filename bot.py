def _all_safe_revealed(session: dict) -> bool:
    rows, cols = session["rows"], session["cols"]
    board, revealed = session["board"], session["revealed"]
    for r in range(rows):
        for c in range(cols):
            if board[r][c] == 0 and not revealed[r][c]:
                return False
    return True

def _reveal_cascade(board, revealed, r, c, rows, cols):
    """Открывает клетку и каскадно открывает пустые соседние."""
    stack = [(r, c)]
    while stack:
        cr, cc = stack.pop()
        if cr < 0 or cr >= rows or cc < 0 or cc >= cols:
            continue
        if revealed[cr][cc]:
            continue
        if board[cr][cc] == 1:
            continue
        revealed[cr][cc] = True
        if _count_around(board, cr, cc) == 0:
            for dr in [-1, 0, 1]:
                for dc in [-1, 0, 1]:
                    if dr == 0 and dc == 0:
                        continue
                    stack.append((cr + dr, cc + dc))

def calc_regen_time(stat_regen: int) -> float:
    """
    stat_regen может быть от -100 до 100.
    При 100%  → 60с
    При 0%    → 3600с
    При -100% → 7200с
    """
    if stat_regen >= 0:
        return max(60, DEFAULT_REGEN_TIME * (1 - stat_regen / 100))
    else:
        return min(7200, DEFAULT_REGEN_TIME * (1 + (-stat_regen) / 100))

def format_time(seconds: float) -> str:
    seconds = int(max(0, seconds))
    h = seconds // 3600
    m = (seconds % 3600) // 60
    s = seconds % 60
    if h > 0:
        return f"{h}ч {m}м {s}с"
    elif m > 0:
        return f"{m}м {s}с"
    return f"{s}с"

def clean_nick(t: str) -> str:
    if not t:
        return "User"
    t = t.strip()
    for ch in ["@", "[", "]", "(", ")", "*", "_", "`", "~"]:
        t = t.replace(ch, "")
    return t or "User"

