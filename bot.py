                next_mines = mines_list[next_round - 1] if next_round - 1 < len(mines_list) else 9
                new_board = _make_board(SAPPER_ROWS, SAPPER_COLS, next_mines)
                new_revealed = [[False] * SAPPER_COLS for _ in range(SAPPER_ROWS)]
